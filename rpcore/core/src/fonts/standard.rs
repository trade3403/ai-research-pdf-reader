#[derive(Debug,Clone,Copy,PartialEq,Eq)]
pub enum StandardFont{Courier,CourierBold,CourierOblique,CourierBoldOblique,Helvetica,HelveticaBold,HelveticaOblique,HelveticaBoldOblique,TimesRoman,TimesBold,TimesItalic,TimesBoldItalic,Symbol,ZapfDingbats}
impl StandardFont{
    pub const ALL:[Self;14]=[Self::Courier,Self::CourierBold,Self::CourierOblique,Self::CourierBoldOblique,Self::Helvetica,Self::HelveticaBold,Self::HelveticaOblique,Self::HelveticaBoldOblique,Self::TimesRoman,Self::TimesBold,Self::TimesItalic,Self::TimesBoldItalic,Self::Symbol,Self::ZapfDingbats];
    pub fn name(self)->&'static [u8]{match self{
        Self::Courier=>b"Courier",Self::CourierBold=>b"Courier-Bold",Self::CourierOblique=>b"Courier-Oblique",Self::CourierBoldOblique=>b"Courier-BoldOblique",
        Self::Helvetica=>b"Helvetica",Self::HelveticaBold=>b"Helvetica-Bold",Self::HelveticaOblique=>b"Helvetica-Oblique",Self::HelveticaBoldOblique=>b"Helvetica-BoldOblique",
        Self::TimesRoman=>b"Times-Roman",Self::TimesBold=>b"Times-Bold",Self::TimesItalic=>b"Times-Italic",Self::TimesBoldItalic=>b"Times-BoldItalic",Self::Symbol=>b"Symbol",Self::ZapfDingbats=>b"ZapfDingbats",
    }}
    pub fn from_name(n:&[u8])->Option<Self>{Self::ALL.into_iter().find(|f|f.name()==n)}
    pub fn default_encoding(self)->&'static [u8]{match self{Self::Symbol=>b"SymbolEncoding",Self::ZapfDingbats=>b"ZapfDingbatsEncoding",_=>b"StandardEncoding"}}
    pub fn width(self,name:&[u8])->Option<f64>{
        if matches!(self,Self::Symbol|Self::ZapfDingbats){
            let table=if self==Self::Symbol{SYMBOL.as_slice()}else{DING.as_slice()};
            return table.iter().find(|(n,_,_)|n.as_bytes()==name).map(|(_,w,_)|f64::from(*w));
        }
        let i=LATIN_NAMES.iter().position(|n|n.as_bytes()==name)?;
        Some(f64::from(match self{
            Self::Courier|Self::CourierBold|Self::CourierOblique|Self::CourierBoldOblique=>600,
            Self::Helvetica|Self::HelveticaOblique=>HELVETICA[i],
            Self::HelveticaBold|Self::HelveticaBoldOblique=>HELVETICA_BOLD[i],
            Self::TimesRoman=>TIMES_ROMAN[i],Self::TimesBold=>TIMES_BOLD[i],Self::TimesItalic=>TIMES_ITALIC[i],Self::TimesBoldItalic=>TIMES_BOLD_ITALIC[i],
            _=>unreachable!(),
        }))
    }
    pub fn unicode(self,name:&[u8])->Option<String>{
        if matches!(name,b"fi"|b"fl"){return Some(if name==b"fi"{"fi"}else{"fl"}.to_string());}
        let code=if matches!(self,Self::Symbol|Self::ZapfDingbats){
            let table=if self==Self::Symbol{SYMBOL.as_slice()}else{DING.as_slice()};
            table.iter().find(|(n,_,_)|n.as_bytes()==name).map(|(_,_,u)|*u)?
        }else{LATIN_UNICODE[LATIN_NAMES.iter().position(|n|n.as_bytes()==name)?]};
        // Private-use construction pieces cannot be confidently exposed as text.
        if (0xe000..=0xf8ff).contains(&code){return None;}
        char::from_u32(code).map(|c|c.to_string())
    }
}
pub fn encoded_name(encoding:&[u8],c:u8)->Option<&'static[u8]>{
    let s=match encoding{b"SymbolEncoding"=>SYMBOL_ENCODING[c as usize],b"ZapfDingbatsEncoding"=>DING_ENCODING[c as usize],_=>return super::cff::predefined_name(encoding,c)};
    if s=="-"{None}else{Some(s.as_bytes())}
}
