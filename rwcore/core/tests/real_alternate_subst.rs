const FONT:&[u8]=include_bytes!("fixtures/alegreyasans/AlegreyaSans-Regular.ttf");
fn with_rules(mut check:impl FnMut(&AlternateSubstitution,&[Pair])){
    let c=parse_font(FONT,FontLimits::default()).unwrap();
    let bytes=c.face(0).unwrap().table(*b"GSUB").unwrap();
    let layout=parse_gsub_layout(bytes,GsubLimits::default()).unwrap();
    assert_eq!(layout.lookups.len(),57);
    let mut seen=0;
    for (i,lookup) in layout.lookups.iter().enumerate(){
        if lookup.kind!=3{continue;}
        for (j,&offset) in lookup.subtables.iter().enumerate(){
            let &(ei,ej,eo,pairs)=&CASES[seen];
            assert_eq!((i,j,offset),(ei,ej,eo));
            let r=parse_alternate_substitution(&bytes[offset..],2109,AlternateSubstLimits::default()).unwrap();
            assert_eq!(r.len(),pairs.len());
            check(&r,pairs);seen+=1;
        }
    }
    assert_eq!(seen,CASES.len());
}
#[test]fn real_full_domain(){
    with_rules(|r,pairs|{
        for id in 0..2109u16{
            let expected=pairs.binary_search_by_key(&id,|p|p.0).ok().map(|i|pairs[i].1);
            assert_eq!(r.alternates(id),expected,"glyph {id}");
        }
    });
}
#[test]fn real_all_candidates_and_atomic_errors(){
    with_rules(|r,pairs|{
        for &(id,seq) in pairs{
            for (index,&out) in seq.iter().enumerate(){
                let mut run=vec![0,id,1];
                assert_eq!(r.select(id,index).unwrap(),Some(out));
                assert!(r.replace_at(&mut run,1,index).unwrap());
                assert_eq!(run,vec![0,out,1]);
            }
            let mut run=vec![0,id,1];
            assert!(r.replace_at(&mut run,1,seq.len()).is_err());
            assert_eq!(run,vec![0,id,1]);
        }
    });
}
#[test]fn existing_gsub_fonts_have_no_direct_type_three(){
    for font in [include_bytes!("fixtures/abeezee/ABeeZee-Regular.ttf").as_slice(),
                 include_bytes!("fixtures/abeezee/ABeeZee-Italic.ttf").as_slice(),
                 include_bytes!("fixtures/arefruqaa/ArefRuqaa-Regular.ttf").as_slice()]{
        let c=parse_font(font,FontLimits::default()).unwrap();
        let b=c.face(0).unwrap().table(*b"GSUB").unwrap();
        let g=parse_gsub_layout(b,GsubLimits::default()).unwrap();
        assert!(!g.lookups.iter().any(|l|l.kind==3));
    }
}
