//! Independently extracted GSUB type 1 mappings from original licensed SFNT fixtures.
use rwcore::*;
type Case = (usize,usize,usize,u16,&'static [(u16,u16)]);
fn check(font:&[u8],glyphs:u32,lookup_count:usize,cases:&[Case]){
    let c=parse_font(font,FontLimits::default()).unwrap();
    let face=c.face(0).unwrap();
    let bytes=face.table(*b"GSUB").unwrap();
    let layout=parse_gsub_layout(bytes,GsubLimits::default()).unwrap();
    assert_eq!(layout.lookups.len(),lookup_count);
    let mut seen=0;
    for (i,lookup) in layout.lookups.iter().enumerate(){
        if lookup.kind!=1{continue;}
        for (j,&offset) in lookup.subtables.iter().enumerate(){
            let &(ei,ej,eo,fmt,pairs)=&cases[seen];
            assert_eq!((i,j,offset),(ei,ej,eo));
            assert_eq!(u16::from_be_bytes([bytes[offset],bytes[offset+1]]),fmt);
            let r=parse_single_substitution(&bytes[offset..],glyphs,SingleSubstLimits::default()).unwrap();
            assert_eq!(r.len(),pairs.len());
            for id in 0..glyphs{
                let expected=pairs.binary_search_by_key(&(id as u16),|p|p.0).ok().map(|z|pairs[z].1);
                assert_eq!(r.substitute(id as u16),expected,"lookup {i}/{j} glyph {id}");
            }
            seen+=1;
        }
    }
    assert_eq!(seen,cases.len());
}
