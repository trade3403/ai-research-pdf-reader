import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { currentPaperPrompt, replacePaperPrompt, removePaperPrompt, shouldFillPaperPrompt } from './src/utils/paperPromptStore.ts';
const read = path => readFileSync(new URL(path, import.meta.url), 'utf8');
let drafts = {};
drafts = replacePaperPrompt(drafts, 'paper-A', '论文来源：第一篇论文.pdf\nPDF 页码：2');
assert.match(currentPaperPrompt(drafts, 'paper-A'), /第一篇论文/);
assert.equal(currentPaperPrompt(drafts, 'paper-B'), '', 'New PDF must never show previous paper prompt');
assert.equal(currentPaperPrompt(drafts, null), '');
assert.equal(shouldFillPaperPrompt('paper-B','paper-A',1,0,drafts['paper-A']), false, 'Switch to B must cancel pending A fill');
assert.equal(shouldFillPaperPrompt('paper-A','paper-A',1,0,drafts['paper-A']), true);
drafts = replacePaperPrompt(drafts, 'paper-B', '论文来源：第二篇论文.pdf\nPDF 页码：1');
assert.match(currentPaperPrompt(drafts, 'paper-B'), /第二篇论文/);
assert.doesNotMatch(currentPaperPrompt(drafts, 'paper-B'), /第一篇论文/);
assert.match(currentPaperPrompt(drafts, 'paper-A'), /第一篇论文/, 'Returning to A restores only its own draft');
assert.equal(shouldFillPaperPrompt('paper-A',null,1,0,drafts['paper-A']), false, 'Returning to A never triggers delayed injection');
assert.equal(shouldFillPaperPrompt('paper-A','paper-A',1,1,drafts['paper-A']), false);
assert.equal(shouldFillPaperPrompt('paper-A','paper-A',2,1,'   '), false);
drafts = removePaperPrompt(drafts, 'paper-A');
assert.equal(currentPaperPrompt(drafts, 'paper-A'), '');
assert.match(currentPaperPrompt(drafts, 'paper-B'), /第二篇论文/);
const app = read('./src/App.tsx');
const dock = read('./src/components/ChatBrowserDock.tsx');
const css = read('./src/styles.css');
const ci = read('./.github/workflows/build-windows-installer.yml');
assert.match(app, /chatPromptByTab/);
assert.match(app, /currentPaperPrompt\(chatPromptByTab, activeId\)/);
assert.match(app, /replacePaperPrompt\(current, active\.id, prompt\)/);
assert.match(app, /removePaperPrompt\(current, id\)/);
assert.match(app, /setChatPromptPendingTabId\(null\)/);
assert.match(app, /shouldFillPaperPrompt\(activeId, chatPromptPendingTabId/);
assert.match(app, /activePaperName=\{active\?\.name \|\| null\}/);
assert.match(dock, /research-chat-prompt-collapsed/);
assert.match(dock, /onClick=\{\(\) => setPromptCollapsed\(value => !value\)\}/);
assert.match(dock, /当前论文：\{activePaperName\}/);
assert.match(dock, /展开提示词/);
assert.match(dock, /隐藏提示词/);
assert.match(css, /chat-prompt-collapsed/);
assert.match(ci, /test:v057/);
console.log('V0.5.7 PDF draft isolation and collapsible prompt panel tests passed');
