import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const read = name => readFileSync(new URL(name, import.meta.url), 'utf8');
const config = JSON.parse(read('./src-tauri/capabilities/default.json'));
const cargo = read('./src-tauri/Cargo.toml');
const app = read('./src/App.tsx');
const dock = read('./src/components/ChatBrowserDock.tsx');
const notes = read('./src/utils/researchClips.ts');
const screen = read('./src/components/ResearchRecords.tsx');
const pkg = JSON.parse(read('./package.json'));
assert.ok(['0.4.0', '0.4.1', '0.4.2', '0.4.3', '0.5.0', '0.5.1', '0.5.2','0.5.3','0.5.5','0.5.6','0.5.7','0.5.8','0.5.9'].includes(pkg.version));
assert.deepEqual(config.webviews, ['main'], 'only trusted local UI may use Tauri APIs');
assert.equal(config.windows, undefined, 'window-level permissions would affect every child webview');
assert.equal(config.remote, undefined, 'remote ChatGPT origin must have no Tauri permissions');
assert.match(cargo, /features = \["unstable"\]/);
assert.ok(config.permissions.includes('core:webview:allow-create-webview'));
assert.ok(config.permissions.includes('core:webview:allow-webview-close'));
assert.ok(config.permissions.includes('clipboard-manager:allow-read-text'));
assert.match(dock, /new Webview\(getCurrentWindow\(\)/);
assert.match(dock, /url: CHATGPT_URL/);
assert.match(dock, /readText\(\)/);
assert.doesNotMatch(dock, /executeJavaScript|querySelector\(.+chatgpt|document\.cookie|fetch\(.+api\/conversation/);
assert.match(app, /mode === 'chat'/);
assert.match(app, /mode === 'records'/);
assert.match(notes, /CREATE TABLE IF NOT EXISTS research_clips/);
assert.match(notes, /normalizeClip/);
assert.match(notes, /validChatGptSource/);
assert.match(screen, /saveClip\(/);
assert.match(screen, /clipsToMarkdown/);
console.log('V0.4 structure + security boundary checks passed');
